"""PostgreSQL schema and idempotent initializer.

This schema is intentionally separate from the SQLite schema. It is not
selected by the running application until repository and auth adapters pass
integration acceptance.
"""
from __future__ import annotations

from database.postgres_connection import PostgresDatabase

POSTGRES_SCHEMA_STATEMENTS = (
    """CREATE TABLE IF NOT EXISTS pc_schema_version (
        id SMALLINT PRIMARY KEY CHECK (id = 1),
        version INTEGER NOT NULL
    )""",
    """INSERT INTO pc_schema_version (id, version) VALUES (1, 1)
       ON CONFLICT (id) DO NOTHING""",
    """CREATE TABLE IF NOT EXISTS projects (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL UNIQUE,
        description TEXT NOT NULL DEFAULT '',
        status TEXT NOT NULL DEFAULT 'active'
            CHECK (status IN ('active', 'archived')),
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS tasks (
        id TEXT PRIMARY KEY,
        project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
        title TEXT NOT NULL,
        description TEXT NOT NULL DEFAULT '',
        assignee TEXT,
        priority TEXT NOT NULL DEFAULT 'medium'
            CHECK (priority IN ('low', 'medium', 'high', 'critical')),
        status TEXT NOT NULL DEFAULT 'todo'
            CHECK (status IN ('todo', 'in_progress', 'blocked', 'done')),
        due_at TEXT,
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS task_dependencies (
        task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
        depends_on_task_id TEXT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
        created_at TEXT NOT NULL,
        PRIMARY KEY (task_id, depends_on_task_id),
        CHECK (task_id <> depends_on_task_id)
    )""",
    """CREATE TABLE IF NOT EXISTS activity_history (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
        task_id TEXT REFERENCES tasks(id) ON DELETE SET NULL,
        event_type TEXT NOT NULL,
        payload_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS pc_users (
        id TEXT PRIMARY KEY,
        email TEXT NOT NULL UNIQUE,
        password_salt BYTEA NOT NULL,
        password_hash BYTEA NOT NULL,
        role TEXT NOT NULL CHECK (role IN ('admin', 'owner', 'editor', 'viewer')),
        enabled SMALLINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
        created_at BIGINT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS pc_project_memberships (
        project_id TEXT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
        user_id TEXT NOT NULL REFERENCES pc_users(id) ON DELETE CASCADE,
        role TEXT NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
        created_at BIGINT NOT NULL,
        PRIMARY KEY (project_id, user_id)
    )""",
    """CREATE TABLE IF NOT EXISTS pc_audit_events (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        actor_id TEXT,
        action TEXT NOT NULL,
        project_id TEXT,
        outcome TEXT NOT NULL,
        created_at BIGINT NOT NULL
    )""",
    """CREATE TABLE IF NOT EXISTS pc_login_attempts (
        email_digest TEXT NOT NULL,
        attempted_at BIGINT NOT NULL,
        succeeded SMALLINT NOT NULL CHECK (succeeded IN (0, 1))
    )""",
    "CREATE INDEX IF NOT EXISTS idx_tasks_project_status ON tasks(project_id, status)",
    "CREATE INDEX IF NOT EXISTS idx_tasks_project_priority ON tasks(project_id, priority)",
    "CREATE INDEX IF NOT EXISTS idx_dependencies_target ON task_dependencies(depends_on_task_id)",
    "CREATE INDEX IF NOT EXISTS idx_activity_project_created ON activity_history(project_id, created_at)",
    "CREATE INDEX IF NOT EXISTS idx_pc_audit_created ON pc_audit_events(created_at)",
    "CREATE INDEX IF NOT EXISTS idx_pc_login_attempts ON pc_login_attempts(email_digest, attempted_at)",
    """CREATE OR REPLACE FUNCTION pc_guard_task_dependency() RETURNS trigger
       LANGUAGE plpgsql AS $$
       DECLARE project_a TEXT; DECLARE project_b TEXT; DECLARE has_cycle BOOLEAN;
       BEGIN
         SELECT project_id INTO project_a FROM tasks WHERE id = NEW.task_id;
         SELECT project_id INTO project_b FROM tasks WHERE id = NEW.depends_on_task_id;
         IF project_a IS NULL OR project_b IS NULL OR project_a <> project_b THEN
           RAISE EXCEPTION 'task dependencies must belong to the same project';
         END IF;
         WITH RECURSIVE reachable(id) AS (
           SELECT NEW.depends_on_task_id
           UNION
           SELECT d.depends_on_task_id
             FROM task_dependencies d JOIN reachable r ON d.task_id = r.id
            WHERE TG_OP <> 'UPDATE'
               OR (d.task_id, d.depends_on_task_id) <>
                  (OLD.task_id, OLD.depends_on_task_id)
         )
         SELECT EXISTS(SELECT 1 FROM reachable WHERE id = NEW.task_id)
           INTO has_cycle;
         IF has_cycle THEN
           RAISE EXCEPTION 'task dependency would create a cycle';
         END IF;
         RETURN NEW;
       END
       $$""",
    """DROP TRIGGER IF EXISTS trg_pc_task_dependency_guard ON task_dependencies""",
    """CREATE TRIGGER trg_pc_task_dependency_guard
       BEFORE INSERT OR UPDATE OF task_id, depends_on_task_id
       ON task_dependencies FOR EACH ROW
       EXECUTE FUNCTION pc_guard_task_dependency()""",
    """CREATE OR REPLACE FUNCTION pc_guard_activity_project() RETURNS trigger
       LANGUAGE plpgsql AS $$
       DECLARE task_project TEXT;
       BEGIN
         IF NEW.task_id IS NOT NULL THEN
           SELECT project_id INTO task_project FROM tasks WHERE id = NEW.task_id;
           IF task_project IS NULL OR task_project <> NEW.project_id THEN
             RAISE EXCEPTION 'activity task must belong to the same project';
           END IF;
         END IF;
         RETURN NEW;
       END
       $$""",
    """DROP TRIGGER IF EXISTS trg_pc_activity_project_guard ON activity_history""",
    """CREATE TRIGGER trg_pc_activity_project_guard
       BEFORE INSERT OR UPDATE OF project_id, task_id
       ON activity_history FOR EACH ROW
       EXECUTE FUNCTION pc_guard_activity_project()""",
    """CREATE OR REPLACE FUNCTION pc_reject_audit_mutation() RETURNS trigger
       LANGUAGE plpgsql AS $$
       BEGIN
         RAISE EXCEPTION 'audit events are immutable';
       END
       $$""",
    """DROP TRIGGER IF EXISTS trg_pc_audit_immutable ON pc_audit_events""",
    """CREATE TRIGGER trg_pc_audit_immutable
       BEFORE UPDATE OR DELETE ON pc_audit_events
       FOR EACH ROW EXECUTE FUNCTION pc_reject_audit_mutation()""",
)


def initialize_postgres_schema(database: PostgresDatabase) -> None:
    """Create the initial PostgreSQL schema atomically and idempotently."""
    with database.transaction() as connection:
        for statement in POSTGRES_SCHEMA_STATEMENTS:
            connection.execute(statement)
        row = connection.execute(
            "SELECT version FROM pc_schema_version WHERE id = 1"
        ).fetchone()
        if row is None or row["version"] > 1:
            raise RuntimeError(
                "PostgreSQL schema version is newer than this application supports"
            )
        connection.execute(
            "UPDATE pc_schema_version SET version = 1 WHERE id = 1"
        )
