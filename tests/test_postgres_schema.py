from database.postgres_schema import POSTGRES_SCHEMA_STATEMENTS, POSTGRES_SCHEMA_VERSION


def test_postgres_schema_covers_core_and_identity_tables():
    sql = "\n".join(POSTGRES_SCHEMA_STATEMENTS)
    for table in (
        "projects", "tasks", "task_dependencies", "activity_history",
        "pc_users", "pc_project_memberships", "pc_audit_events",
        "pc_login_attempts",
    ):
        assert f"CREATE TABLE IF NOT EXISTS {table}" in sql


def test_postgres_schema_preserves_database_level_guards():
    sql = "\n".join(POSTGRES_SCHEMA_STATEMENTS)
    assert "pc_guard_task_dependency" in sql
    assert "pc_guard_activity_project" in sql
    assert "pc_reject_audit_mutation" in sql
    assert "audit events are immutable" in sql


def test_postgres_schema_uses_postgresql_types_and_identity_columns():
    sql = "\n".join(POSTGRES_SCHEMA_STATEMENTS)
    assert "BYTEA" in sql
    assert "GENERATED BY DEFAULT AS IDENTITY" in sql


def test_postgres_schema_version_matches_current_sqlite_schema_version():
    from database.schema import SCHEMA_VERSION
    assert POSTGRES_SCHEMA_VERSION == SCHEMA_VERSION == 2
